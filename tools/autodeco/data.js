// Writes tm_autodeco_data.js, the tables Auto deco (tm_autodeco.js) runs on:
// - stock: every stock part's name -> id, and cat: id -> the game's category (which parts are road);
// - turn: how each of the 24 orientations (rot, up-axis) changes when a part is turned about the vertical (verified
//   against the game's quaternions);
// - twins: the stock blocks that fit right under each driving part's deck (tools/autodeco/twins.js).
// node tools/autodeco/data.js
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const STOCK_IDS = require('./stock_ids.json');
const ORIENT = require('./orient.json');
const twins = require('./twins.json');
// The stock categories, by id (module 2600's part list, fixed since 0.5).
const CATS = require('./stock_cats.json');

const qmul = (a, b) => [
  a[3] * b[0] + a[0] * b[3] + a[1] * b[2] - a[2] * b[1],
  a[3] * b[1] - a[0] * b[2] + a[1] * b[3] + a[2] * b[0],
  a[3] * b[2] + a[0] * b[1] - a[1] * b[0] + a[2] * b[3],
  a[3] * b[3] - a[0] * b[0] - a[1] * b[1] - a[2] * b[2],
];
const qOf = (rot, axis) => ORIENT.find((o) => o[0] === rot && o[1] === axis).slice(2);
const same = (a, b) => Math.abs(a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3]) > 0.999;
const RY = (k) => [0, Math.sin((Math.PI / 4) * k), 0, Math.cos((Math.PI / 4) * k)];
// turn[rot * 6 + axis][k] = rot' * 6 + axis' after k quarter turns counter-clockwise seen from above.
const turn = [];
for (let r = 0; r < 4; r++)
  for (let a = 0; a < 6; a++) {
    const row = [];
    for (let k = 0; k < 4; k++) {
      const q = qmul(RY(k), qOf(r, a));
      const hit = ORIENT.find((o) => same(o.slice(2), q));
      row.push(hit[0] * 6 + hit[1]);
    }
    turn[r * 6 + a] = row;
  }

const tw = {};
for (const [id, v] of Object.entries(twins)) tw[id] = v.t;

const data = { version: 1, stock: STOCK_IDS, cat: CATS, turn, twins: tw };
const out =
  '// Generated by tools/autodeco/data.js. Do not edit by hand.\n' +
  '// Tables for Auto deco (tm_autodeco.js): stock part ids and categories, orientation turns, and the stock blocks that\n' +
  '// fit under each driving part (tools/autodeco/twins.js).\n' +
  'self.TM_AUTODECO = ' +
  JSON.stringify(data) +
  ';\n';
fs.writeFileSync(path.join(ROOT, 'tm_autodeco_data.js'), out);
console.log('tm_autodeco_data.js', (out.length / 1024).toFixed(0) + ' KB,', Object.keys(tw).length, 'twins');
